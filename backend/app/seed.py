def seed() -> int:
    init_db()
    with get_conn() as conn:
        conn.execute("DELETE FROM products")
        conn.executemany(
            """INSERT INTO products
               (name, category, brand, material, spec, model, size, length, standard,
                process, origin, industry, price, unit, moq, stock, lead_time, description)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            PRODUCTS,
        )
        count = conn.execute("SELECT COUNT(*) FROM products").fetchone()[0]
    return count


